def setup_logging(log_file: Optional[Path] = None, verbose: bool = False) -> None:
    """Configure structured console logging with optional file output."""
    fmt = "%(asctime)s %(levelname)s %(message)s"
    handlers = [logging.StreamHandler(sys.stderr)]
    if log_file is not None:
        handlers.append(logging.FileHandler(log_file, encoding="utf-8"))
    level = logging.DEBUG if verbose else logging.INFO
    logging.basicConfig(level=level, format=fmt, handlers=handlers)


# ---------------------------------------------------------------------------
# Clip planning
# ---------------------------------------------------------------------------

def plan_clips(
    source_path: str,
    fps: float,
    duration: float,
    clip_duration: float,
    clip_stride: float,
) -> List[ClipPlan]:
    """Plan non-overlapping (or strided) clips across the full video duration.

    Clips are generated by stepping through [0, duration) with the given stride.
    Each clip has exactly ``clip_duration`` seconds. The last clip may be
    shorter if the video does not divide evenly.
    """
    if clip_duration <= 0:
        raise ValueError(f"clip_duration must be positive, got {clip_duration}")
    if clip_stride <= 0:
        raise ValueError(f"clip_stride must be positive, got {clip_stride}")
    if fps <= 0:
        raise ValueError(f"fps must be positive, got {fps}")
    if duration <= 0:
        return []

    # Compute number of frames per clip deterministically
    num_frames_per_clip = max(1, int(round(clip_duration * fps)))

    clips: List[ClipPlan] = []
    t = 0.0
    clip_idx = 0
    while t < duration:
        end = min(t + clip_duration, duration)
        if end <= t:
            break
        # Output path is deterministic: video_root / clip_XXXXX.pt
        safe_name = Path(source_path).stem
        out_name = f"{safe_name}_clip{clip_idx:06d}.pt"
        clips.append(
            ClipPlan(
                source_path=source_path,
                start_ts=round(t, 6),
                end_ts=round(end, 6),
                num_frames=num_frames_per_clip,
                output_path=out_name,
            )
        )
        t += clip_stride
        clip_idx += 1

    return clips


# ---------------------------------------------------------------------------
# Frame extraction
# ---------------------------------------------------------------------------

def _decode_clip_impl(
    video_handle,
    start_ts: float,
    end_ts: float,
    target_fps: float,
    spatial_size: Tuple[int, int],
) -> "torch.Tensor":
    """Decode frames from start_ts to end_ts and resample to target_fps.

    Returns C x T x H x W float32 tensor in [-1, 1] approx range.
    """
    torch = _import_torch()
    fps = video_handle.get_video_info()["video_fps"]
    if fps <= 0:
        raise ValueError(f"Invalid video fps: {fps}")

    start_frame = int(start_ts * fps)
    end_frame = int(end_ts * fps)
    num_frames_requested = max(1, end_frame - start_frame)

    raw = video_handle.decode_video(start_frame, end_frame)
    if raw is None:
        raise ValueError("decode_video returned None")

    tensor = torch.from_numpy(raw.astype("float32") / 255.0)  # (T, H, W, C)

    # Temporal resampling
    clip_duration = end_ts - start_ts
    T, H, W, C = tensor.shape
    if target_fps > 0 and abs(fps - target_fps) > 1e-9:
        new_T = max(1, int(round(clip_duration * target_fps)))
        if new_T != T:
            tensor = tensor.permute(3, 0, 1, 2)
            tensor = tensor.unsqueeze(0)
            tensor = torch.nn.functional.interpolate(
                tensor, size=(new_T, H, W), mode="bilinear", align_corners=False
            )
            tensor = tensor.squeeze(0)
            tensor = tensor.permute(1, 2, 3, 0)

    # Spatial resize
    th, tw = spatial_size
    if (H, W) != (th, tw):
        tensor = tensor.permute(3, 0, 1, 2)
        tensor = torch.nn.functional.interpolate(
            tensor, size=(th, tw), mode="bilinear", align_corners=False
        )
        tensor = tensor.permute(1, 2, 3, 0)

    # ImageNet normalization
    tensor = tensor - torch.tensor([0.485, 0.456, 0.406], dtype=tensor.dtype, device=tensor.device)
    tensor = tensor / torch.tensor([0.229, 0.224, 0.225], dtype=tensor.dtype, device=tensor.device)

    tensor = tensor.permute(3, 0, 1, 2)  # C x T x H x W
    return tensor


# ---------------------------------------------------------------------------
# Clip extraction worker
# ---------------------------------------------------------------------------

def _extract_clip(
    clip: ClipPlan,
    output_dir: Path,
    target_fps: float,
    spatial_size: Tuple[int, int],
    overwrite: bool,
) -> ClipResult:
    """Extract a single clip and save it atomically."""
    out_path = Path(output_dir) / clip.output_path

    # Resume: skip if already present and overwrite is False
    if out_path.exists() and not overwrite:
        return ClipResult(
            clip_path=str(out_path),
            success=True,
            tensor_shape=None,
            source_path=clip.source_path,
            start_ts=clip.start_ts,
            end_ts=clip.end_ts,
        )

    try:
        PyTorchVideo = _import_pytorchvideo()
        video = PyTorchVideo.from_file(clip.source_path)
        info = video.get_video_info()
        fps = info.get("video_fps", 0.0)

        tensor = _decode_clip_impl(video, clip.start_ts, clip.end_ts, target_fps, spatial_size)

        # Atomic write: save to temp file then rename
        with tempfile.NamedTemporaryFile(
            dir=str(output_dir), suffix=".pt", delete=False
        ) as tmp:
            tmp_path = tmp.name
        try:
            torch = _import_torch()
            torch.save(tensor, tmp_path)
            os.replace(tmp_path, str(out_path))
        except Exception:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)
            raise

        shape = list(tensor.shape)
        return ClipResult(
            clip_path=str(out_path),
            success=True,
            tensor_shape=shape,
            source_path=clip.source_path,
            start_ts=clip.start_ts,
            end_ts=clip.end_ts,
            fps=fps,
            num_frames=shape[1] if len(shape) > 1 else 0,
            spatial_size=(shape[2], shape[3]) if len(shape) > 3 else (0, 0),
        )

    except Exception as exc:
        logger.warning("Failed to extract clip %s: %s", clip.output_path, exc)
        return ClipResult(
            clip_path=str(out_path),
            success=False,
            error=str(exc),
            source_path=clip.source_path,
            start_ts=clip.start_ts,
            end_ts=clip.end_ts,
        )


# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------

def write_manifest(
    results: List[ClipResult],
    manifest_path: Path,
) -> None:
    """Append clip results as JSONL lines."""
    with open(manifest_path, "a", encoding="utf-8") as fh:
        for res in results:
            entry = {
                "source_path": res.source_path,
                "clip_path": res.clip_path,
                "start_ts": res.start_ts,
                "end_ts": res.end_ts,
                "tensor_shape": res.tensor_shape,
                "fps": res.fps,
                "num_frames": res.num_frames,
                "spatial_size": list(res.spatial_size),
                "success": res.success,
            }
            if res.error:
                entry["error"] = res.error
            fh.write(json.dumps(entry, default=str) + "\n")


# ---------------------------------------------------------------------------
# Main extractor
# ---------------------------------------------------------------------------

def extract(
    input_dir: Path,
    output_dir: Path,
    clip_duration: float,
    clip_stride: float,
    target_fps: float,
    spatial_size: Tuple[int, int],
    overwrite: bool,
    num_workers: int,
    resume: bool,
    log_file: Optional[Path],
    verbose: bool,
) -> None:
    """Run the full extraction pipeline."""
    setup_logging(log_file, verbose)
    logger.info("Starting video pre-extractor")
    logger.info(
        "input=%s output=%s clip_duration=%s clip_stride=%s target_fps=%s spatial_size=%s overwrite=%s resume=%s workers=%s",
        input_dir,
        output_dir,
        clip_duration,
        clip_stride,
        target_fps,
        spatial_size,
        overwrite,
        resume,
        num_workers,
    )

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    manifest_path = output_dir / "manifest.jsonl"
    # Resume: don't truncate existing manifest unless overwrite
    if not resume and manifest_path.exists():
        # Back up old manifest
        backup = manifest_path.with_suffix(".jsonl.bak")
        manifest_path.rename(backup)
        logger.info("Backed up existing manifest to %s", backup)

    # Discover videos
    video_paths = sorted(
        p for p in input_dir.rglob("*.mp4") if p.is_file()
    )
    logger.info("Discovered %d MP4 file(s) in %s", len(video_paths), input_dir)

    all_results: List[ClipResult] = []
    failed_videos: List[str] = []
    lock = Lock()

    def process_one(source_path: str) -> List[ClipResult]:
        """Extract all clips for a single video."""
        results: List[ClipResult] = []
        try:
            PyTorchVideo = _import_pytorchvideo()
            video = PyTorchVideo.from_file(source_path)
            info = video.get_video_info()
            fps = info.get("video_fps", 0.0)
            duration = info.get("duration", 0.0)
            spatial = info.get("image_size", (224, 224))
            if isinstance(spatial, list):
                spatial = tuple(spatial)
            num_frames = info.get("num_frames", 0)

            if fps <= 0 or duration <= 0:
                logger.warning("Skipping unreadable video %s: fps=%s duration=%s", source_path, fps, duration)
                failed_videos.append(source_path)
                return results

            video_meta = VideoInfo(
                fps=fps,
                duration=duration,
                num_frames=num_frames,
                spatial_size=spatial,
                source_path=source_path,
            )
            logger.info(
                "Video %s: fps=%s duration=%ss num_frames=%s",
                source_path,
                video_meta.fps,
                duration,
                video_meta.num_frames,
            )

            clips = plan_clips(
                source_path=source_path,
                fps=fps,
                duration=duration,
                clip_duration=clip_duration,
                clip_stride=clip_stride,
            )
            logger.info("Planned %d clip(s) for %s", len(clips), source_path)

            for clip in clips:
                res = _extract_clip(
                    clip,
                    output_dir,
                    target_fps,
                    spatial_size,
                    overwrite,
                )
                results.append(res)

                with lock:
                    all_results.append(res)
                    if not res.success:
                        failed_videos.append(source_path)

        except Exception as exc:
            logger.warning("Failed to process video %s: %s", source_path, exc)
            failed_videos.append(source_path)

        return results

    # Process sequentially (EncodedVideo holds file handles; threading complicates)
    for idx, vp in enumerate(video_paths, 1):
        logger.info("[%d/%d] Processing %s", idx, len(video_paths), vp)
        process_one(str(vp))

    # Write manifest
    write_manifest(all_results, manifest_path)

    # Summary
    total_clips = len(all_results)
    success_clips = sum(1 for r in all_results if r.success)
    failed_clips = total_clips - success_clips
    logger.info("Processing complete:")
    logger.info("  Videos discovered : %d", len(video_paths))
    logger.info("  Videos failed     : %d", len(failed_videos))
    logger.info("  Clips planned     : %d", total_clips)
    logger.info("  Clips succeeded   : %d", success_clips)
    logger.info("  Clips failed      : %d", failed_clips)
    logger.info("  Manifest          : %s", manifest_path)

    if failed_videos:
        logger.warning("Failed videos:")
        for fv in failed_videos:
            logger.warning("  %s", fv)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Recursively extract video clips for ML training pipelines.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--input", required=True, type=Path, help="Root directory containing raw MP4 files")
    parser.add_argument("--output", required=True, type=Path, help="Directory to write extracted .pt clips and manifest")
    parser.add_argument("--clip-duration", type=float, default=2.0, help="Duration of each clip in seconds (default: 2.0)")
    parser.add_argument("--clip-stride", type=float, default=1.0, help="Stride between consecutive clips in seconds (default: 1.0)")
    parser.add_argument("--target-fps", type=float, default=16.0, help="Target frames-per-second for output clips (default: 16)")
    parser.add_argument("--spatial-size", type=int, nargs=2, default=[224, 224], help="Output spatial dimensions H W (default: 224 224)")
    parser.add_argument("--workers", type=int, default=1, help="Number of worker threads (default: 1)")
    parser.add_argument("--overwrite", action="store_true", help="Overwrite existing clips")
    parser.add_argument("--resume", action="store_true", help="Skip already-extracted clips")
    parser.add_argument("--log-file", type=Path, help="Optional log file path")
    parser.add_argument("--verbose", action="store_true", help="Enable debug-level logging")
    return parser.parse_args(argv)


def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    extract(
        input_dir=args.input,
        output_dir=args.output,
        clip_duration=args.clip_duration,
        clip_stride=args.clip_stride,
        target_fps=args.target_fps,
        spatial_size=tuple(args.spatial_size),
        overwrite=args.overwrite,
        num_workers=args.workers,
        resume=args.resume,
        log_file=args.log_file,
        verbose=args.verbose,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

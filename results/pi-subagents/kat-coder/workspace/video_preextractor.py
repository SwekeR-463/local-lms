"""
Video Pre-Extractor for Machine-Learning Datasets

Recursively reads raw MP4 files, converts them into clips suitable for
PyTorchVideo / PyTorch training pipelines, and emits a JSONL manifest.

Usage
-----
    python video_preextractor.py \
        --input  /path/to/raw_videos \
        --output /path/to/extracted_clips \
        --clip-duration 2.0 \
        --clip-stride 1.0 \
        --target-fps 16 \
        --spatial-size 224

Dependencies
------------
    pip install torch torchvision torchaudio
    pip install pytorchvideo
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from threading import Lock
from typing import BinaryIO, Iterator, List, Optional, Tuple

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Lazy import helpers — modules are loaded on first use so tests can mock
# the boundaries without needing real installations.
# ---------------------------------------------------------------------------

_torch = None
_PyTorchVideo = None


def _import_torch():
    global _torch
    if _torch is None:
        try:
            import torch as _t
            _torch = _t
        except ImportError as exc:
            raise ImportError(
                "torch not installed. Install with:\n"
                "  pip install torch torchvision torchaudio"
            ) from exc
    return _torch


def _import_pytorchvideo():
    global _PyTorchVideo
    if _PyTorchVideo is None:
        try:
            from pytorchvideo.data.encoded_video import EncodedVideo as _Ev
            _PyTorchVideo = _Ev
        except ImportError as exc:
            raise ImportError(
                "pytorchvideo not installed. Install with:\n"
                "  pip install pytorchvideo"
            ) from exc
    return _PyTorchVideo


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------

@dataclass
class VideoInfo:
    """Metadata extracted from a single video file."""

    fps: float
    duration: float
    num_frames: int
    spatial_size: Tuple[int, int]
    source_path: str

    @property
    def num_clips(self) -> int:
        if self.fps <= 0 or self.duration <= 0:
            return 0
        return int(self.duration * self.fps)


@dataclass
class ClipPlan:
    """A single clip to extract from a video."""

    source_path: str
    start_ts: float
    end_ts: float
    num_frames: int
    output_path: str


@dataclass
class ClipResult:
    """Result of extracting a single clip."""

    clip_path: str
    success: bool
    tensor_shape: Optional[List[int]] = None
    error: Optional[str] = None
    source_path: str = ""
    start_ts: float = 0.0
    end_ts: float = 0.0
    fps: float = 0.0
    num_frames: int = 0
    spatial_size: Tuple[int, int] = (0, 0)


# ---------------------------------------------------------------------------
# Logging

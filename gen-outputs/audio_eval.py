    print(f"  Recall   :  {metrics['recall']:.4f}")
    print(f"  F1 Score :  {metrics['f1_score']:.4f}")
    if "eer" in metrics:
        print(f"  EER      :  {metrics['eer']:.4f}")
    if "auc" in metrics and metrics["auc"] is not None:
        print(f"  AUC      :  {metrics['auc']:.4f}")
    per_class = metrics.get("per_class_auc", {})
    if per_class:
        print("  Per-class AUC:")
        for cls, val in per_class.items():
            print(f"    {cls}: {val:.4f}")
    print("=" * 60)
    print("  Classification Report:")
    for cls, stats in metrics["classification_report"].items():
        if isinstance(stats, dict):
            print(f"    {cls:15s}  prec={stats.get('precision', 0):.4f}  "
                  f"rec={stats.get('recall', 0):.4f}  f1={stats.get('f1-score', 0):.4f}  "
                  f"sup={stats.get('support', 0)}")
    print("=" * 60)



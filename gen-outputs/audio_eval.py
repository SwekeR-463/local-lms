def compute_eer(scores: np.ndarray, labels: np.ndarray) -> float:
    """Compute Equal Error Rate (EER) from raw scores and binary labels.

    EER is the point where False Acceptance Rate equals False Rejection Rate.
    Lower is better.
    """
    # [GENERATED by KAT-Coder] EER algorithm is correct
    pos_scores = scores[labels == 1]
    neg_scores = scores[labels == 0]

    if pos_scores.size == 0 or neg_scores.size == 0:
        return 1.0

    thresholds = np.sort(np.unique(np.concatenate([pos_scores, neg_scores])))[::-1]
    if thresholds.size == 0:
        return 1.0

    far_list, frr_list = [], []
    for thresh in thresholds:
        far = (neg_scores >= thresh).mean()
        frr = (pos_scores < thresh).mean()
        far_list.append(far)
        frr_list.append(frr)

    far_arr = np.array(far_list)
    frr_arr = np.array(frr_list)
    idx = np.argmin(np.abs(far_arr - frr_arr))
    return float((far_arr[idx] + frr_arr[idx]) / 2.0)


def compute_det_curve(scores: np.ndarray, labels: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Compute Detection Error Tradeoff curve (FAR, FRR, thresholds).

    [GENERATED by KAT-Coder]
    """
    thresholds = np.sort(np.unique(scores))[::-1]
    pos_scores = scores[labels == 1]
    neg_scores = scores[labels == 0]
    far_list, frr_list, thresh_list = [], [], []

    for thresh in thresholds:
        far = (neg_scores >= thresh).mean() if neg_scores.size > 0 else 0.0
        frr = (pos_scores < thresh).mean() if pos_scores.size > 0 else 0.0
        far_list.append(far)
        frr_list.append(frr)
        thresh_list.append(thresh)

    return np.array(far_list), np.array(frr_list), np.array(thresh_list)


def evaluate_audio_classification(
    y_true: Union[np.ndarray, List],
    y_pred: Union[np.ndarray, List],
    y_scores: Optional[Union[np.ndarray, List]] = None,
    class_names: Optional[List[str]] = None,
    task_type: str = "binary",
    output_dir: str = "eval_results",
    save_plots: bool = True,
) -> Dict:
    """Evaluate an audio classification model.

    Parameters
    ----------
    y_true : shape (n_samples,)
        Ground truth labels.
    y_pred : shape (n_samples,)
        Predicted labels.
    y_scores : shape (n_samples,) for binary, (n_samples, n_classes) for multiclass
        Confidence scores. Required for EER/DET/ROC/PR curves.
    class_names : list of str, optional
        Human-readable class names for plots.
    task_type : "binary" or "multiclass"
    output_dir : str
        Directory to save plots.
    save_plots : bool
        Whether to write figures to disk.

    Returns
    -------
    dict with keys: accuracy, precision, recall, f1_score, confusion_matrix,
    classification_report, eer (binary only), auc, det_far/frr/thresholds,
    prec_curve, rec_curve, average_precision.
    """
    # [GENERATED by KAT-Coder] Core metric computation
    y_true = np.asarray(y_true).ravel()
    y_pred = np.asarray(y_pred).ravel()
    n_classes = len(np.unique(np.concatenate([y_true, y_pred])))

    # [ENHANCED by dsv4-pro] validate shapes
    if y_scores is not None:
        y_scores = np.asarray(y_scores)
        if y_scores.ndim == 1:
            pass  # binary scores, OK
        elif y_scores.ndim == 2 and task_type == "multiclass":
            pass  # per-class scores, OK
        else:
            y_scores = np.max(y_scores, axis=1)

    average = "binary" if task_type == "binary" else "weighted"
    acc = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred, average=average, zero_division=0)
    recall = recall_score(y_true, y_pred, average=average, zero_division=0)
    f1 = f1_score(y_true, y_pred, average=average, zero_division=0)
    cm = confusion_matrix(y_true, y_pred)

    if class_names is None:
        class_names = [str(c) for c in sorted(np.unique(np.concatenate([y_true, y_pred])))]

    metrics = {
        "accuracy": float(acc),
        "precision": float(precision),
        "recall": float(recall),
        "f1_score": float(f1),
        "confusion_matrix": cm,
        "classification_report": classification_report(
            y_true, y_pred, target_names=class_names, output_dict=True, zero_division=0
        ),
        "class_names": class_names,
    }

    # EER and DET: binary or one-vs-rest for multiclass
    if y_scores is not None and y_scores.ndim == 1 and task_type == "binary":
        # [GENERATED by KAT-Coder] EER/DET for binary case — correct
        eer = compute_eer(y_scores, y_true.astype(int))
        metrics["eer"] = float(eer)
        far, frr, thresholds = compute_det_curve(y_scores, y_true.astype(int))
        metrics["det_far"] = far.tolist()      # [FIXED by dsv4-pro] convert ndarray for JSON safety
        metrics["det_frr"] = frr.tolist()
        metrics["det_thresholds"] = thresholds.tolist()
        try:
            metrics["auc"] = float(roc_auc_score(y_true, y_scores))
        except Exception:
            metrics["auc"] = None

        prec, rec, _ = precision_recall_curve(y_true, y_scores)
        metrics["prec_curve"] = prec.tolist()
        metrics["rec_curve"] = rec.tolist()
        metrics["average_precision"] = float(np.trapezoid(prec, rec))  # [FIXED by dsv4-pro] np.trapz removed in numpy 2.x

    elif y_scores is not None and task_type == "multiclass":
        # [FIXED by dsv4-pro] KAT-Coder used y_scores[mask] which selects wrong samples.
        # Correct approach: binarize labels (one-vs-rest), then compute per-class ROC.
        y_true_bin = label_binarize(y_true, classes=sorted(np.unique(y_true)))
        metrics["per_class_auc"] = {}
        try:
            for i, cls_name in enumerate(class_names):
                if i >= y_true_bin.shape[1]:
                    break
                col = y_true_bin[:, i]
                if col.sum() == 0 or (col == 1).all():
                    continue  # skip classes with only one label
                score_col = y_scores[:, i] if y_scores.ndim > 1 else y_scores
                metrics["per_class_auc"][cls_name] = float(roc_auc_score(col, score_col))
        except Exception:
            metrics["per_class_auc"] = {}

    if save_plots:
        os.makedirs(output_dir, exist_ok=True)
        _plot_all(metrics, y_true, y_pred, y_scores, class_names, task_type, output_dir)
        _print_summary(metrics, class_names)

    return metrics


